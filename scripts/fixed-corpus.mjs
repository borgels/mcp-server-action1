#!/usr/bin/env node
// Writes src/fixed-corpus.generated.ts: every string literal in src/ (and the static parts of every template
// literal) of 6 characters or more, read with the TypeScript parser. A gateway refuses a key that shares a piece of 6
// characters with any of them, so no text of our own can ever hold a piece of a key. `--check` exits 1 when the file
// is out of date (run by test/fixed-corpus.test.ts), so a new text cannot be forgotten.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import ts from 'typescript';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const SRC = join(ROOT, 'src');
const OUT = join(SRC, 'fixed-corpus.generated.ts');
const MIN = 6;

function files(dir) {
  return readdirSync(dir, { withFileTypes: true }).flatMap(entry => {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) return files(path);
    return entry.name.endsWith('.ts') && path !== OUT ? [path] : [];
  });
}

export function corpus() {
  const found = new Set();
  for (const path of files(SRC).sort()) {
    const text = readFileSync(path, 'utf8').replace(/\r\n/g, '\n');
    const source = ts.createSourceFile(relative(ROOT, path), text, ts.ScriptTarget.Latest, true);
    const visit = node => {
      if (ts.isStringLiteral(node) || ts.isNoSubstitutionTemplateLiteral(node)) found.add(node.text);
      else if (ts.isTemplateExpression(node)) {
        found.add(node.head.text);
        for (const span of node.templateSpans) found.add(span.literal.text);
      }
      ts.forEachChild(node, visit);
    };
    visit(source);
  }
  return [...found].filter(value => value.length >= MIN).sort();
}

export function render(values) {
  return [
    '// Generated by scripts/fixed-corpus.mjs; do not edit. Every string literal of 6 characters or more in src/.',
    '// A gateway refuses a key that shares a piece of 6 characters with any of them (see src/key-admission.ts).',
    'export const FIXED_CORPUS: readonly string[] = [',
    ...values.map(value => `  ${JSON.stringify(value)},`),
    '];',
    '',
  ].join('\n');
}

const values = corpus();
if (process.argv.includes('--check')) {
  // Compared as sets: a text rename (scripts/rename.mjs in the template) may change the order, not the content.
  let current = new Set();
  try {
    const lines = readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n').split('\n');
    current = new Set(lines.filter(line => /^ {2}".*",$/.test(line)).map(line => JSON.parse(line.trim().slice(0, -1))));
  } catch {
    current = new Set();
  }
  if (current.size !== values.length || !values.every(value => current.has(value))) {
    process.stderr.write('src/fixed-corpus.generated.ts is out of date: run node scripts/fixed-corpus.mjs\n');
    process.exit(1);
  }
} else {
  writeFileSync(OUT, render(values));
}
